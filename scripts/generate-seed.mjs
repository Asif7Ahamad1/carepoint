const escape = (value) => String(value).replaceAll("\\", "\\\\").replaceAll("'", "''");
const quote = (value) => `'${escape(value)}'`;
const sqlRows = (rows) => rows.map((row) => `(${row.map((value) => value === null ? "NULL" : typeof value === "number" ? value : quote(value)).join(", ")})`).join(",\n");
const idFor = (number) => `00000000-0000-4000-8000-${number.toString(16).padStart(12, "0")}`;
function clinicDateTime(date, minutes) {
  const hour = String(Math.floor(minutes / 60)).padStart(2, "0");
  const minute = String(minutes % 60).padStart(2, "0");
  const [year, month, day] = date.split("-").map(Number);
  const target = Date.UTC(year, month - 1, day, Number(hour), Number(minute));
  let timestamp = target;
  for (let attempt = 0; attempt < 4; attempt += 1) {
    const parts = new Intl.DateTimeFormat("en-GB", {
      timeZone,
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      hourCycle: "h23",
    }).formatToParts(new Date(timestamp));
    const values = Object.fromEntries(parts.map(({ type, value }) => [type, Number(value)]));
    const represented = Date.UTC(values.year, values.month - 1, values.day, values.hour, values.minute);
    const delta = target - represented;
    timestamp += delta;
    if (delta === 0) return new Date(timestamp);
  }
  throw new Error(`Local time does not exist in ${timeZone}: ${date} ${hour}:${minute}`);
}

