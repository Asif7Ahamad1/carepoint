const appointments = [];
const startDate = new Date("2026-06-01T12:00:00Z");
let patientNumber = 1;
let sequence = 1;
for (let dayOffset = 0; appointments.length < 3000; dayOffset += 1) {
  const date = new Date(startDate);
  date.setUTCDate(date.getUTCDate() + dayOffset);
  const weekday = date.getUTCDay();
  if (weekday === 0 || weekday === 6) continue;
  const day = date.toISOString().slice(0, 10);
  for (const [doctorId] of doctors) {
    let token = 0;
    for (const [begin, end] of [[10 * 60, 14 * 60], [17 * 60, 20 * 60]]) {
      for (let minute = begin; minute + 20 <= end && appointments.length < 3000; minute += 20) {
        const hour = String(Math.floor(minute / 60)).padStart(2, "0");
        const mins = String(minute % 60).padStart(2, "0");
        const startsAt = clinicDateTime(day, minute).toISOString();
        const endsAt = new Date(Date.parse(startsAt) + 20 * 60_000).toISOString().replace("T", " ").replace("Z", "");
        const startSql = startsAt.replace("T", " ").replace("Z", "");
        const patientId = `patient-${String(patientNumber).padStart(4, "0")}`;
        const status = sequence % 19 === 0 ? "CANCELLED" : sequence % 13 === 0 ? "CHECKED_IN" : "COMPLETED";
        const tokenNumber = ++token;
        const id = idFor(sequence);
        appointments.push([id, doctorId, patientId, startSql, endsAt, status, tokenNumber]);
        patientNumber = patientNumber === 3000 ? 1 : patientNumber + 1;
        sequence += 1;
      }
    }
  }
}

